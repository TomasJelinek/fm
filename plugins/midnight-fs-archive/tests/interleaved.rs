use midnight_filesystem_api::{Format, Kind};
use midnight_fs_archive::{Archive, Limits};

// Independently constructed 7z COPY fixture: one solid block with a block-only CRC.
// Files in header order: streamed "a"="first", no-stream "empty", directory "dir",
// zero-length streamed "zero", streamed "b"="other". Header and block CRCs are valid.
const INTERLEAVED: &[u8] = &[
    0x37, 0x7a, 0xbc, 0xaf, 0x27, 0x1c, 0x00, 0x04, 0x5f, 0xb3, 0x4e, 0xc0, 0x0a, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x53, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x05, 0x69, 0x49, 0x56,
    0x66, 0x69, 0x72, 0x73, 0x74, 0x6f, 0x74, 0x68, 0x65, 0x72, 0x01, 0x04, 0x06, 0x00, 0x01, 0x09,
    0x0a, 0x00, 0x07, 0x0b, 0x01, 0x00, 0x01, 0x01, 0x00, 0x0c, 0x0a, 0x0a, 0x01, 0x0f, 0xfa, 0x8f,
    0x73, 0x00, 0x08, 0x0d, 0x03, 0x09, 0x05, 0x00, 0x00, 0x00, 0x05, 0x05, 0x11, 0x27, 0x00, 0x61,
    0x00, 0x00, 0x00, 0x65, 0x00, 0x6d, 0x00, 0x70, 0x00, 0x74, 0x00, 0x79, 0x00, 0x00, 0x00, 0x64,
    0x00, 0x69, 0x00, 0x72, 0x00, 0x00, 0x00, 0x7a, 0x00, 0x65, 0x00, 0x72, 0x00, 0x6f, 0x00, 0x00,
    0x00, 0x62, 0x00, 0x00, 0x00, 0x0e, 0x01, 0x60, 0x0f, 0x01, 0x80, 0x00, 0x00,
];

#[test]
fn solid_stream_ordinals_ignore_interleaved_metadata_only_entries() {
    let mut archive =
        Archive::open(Format::SevenZip, INTERLEAVED.to_vec(), Limits::default()).unwrap();
    let nodes = archive.list(1, 0).unwrap();
    assert_eq!(
        nodes.iter().map(|n| n.display.as_str()).collect::<Vec<_>>(),
        ["a", "empty", "dir", "zero", "b"]
    );
    assert_eq!(nodes[2].kind, Kind::Directory);
    assert_eq!(archive.read(nodes[1].id, 0, 1).unwrap(), (vec![], true));
    assert_eq!(archive.read(nodes[0].id, 0, 5).unwrap().0, b"first");
    assert_eq!(archive.read(nodes[4].id, 0, 5).unwrap().0, b"other");
    assert_eq!(archive.read(nodes[3].id, 0, 1).unwrap(), (vec![], true));
}
