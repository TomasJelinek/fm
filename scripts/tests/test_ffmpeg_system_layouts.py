"""The Linux system decoder's FFmpeg ABI tables match each release's public headers.

plugins/midnight-thumbnail-video/src/system/linux/ffmpeg/layouts.rs is generated by
scripts/generate-ffmpeg-system-layouts.py from the headers of the first and the last release of
every supported libavcodec series (58 to 63). With MIDNIGHT_FFMPEG_HEADERS naming a folder that
holds one subfolder of extracted public headers per release (4.0, 4.4.8, ..., 9.1; see the
generator's help), the generator recompiles its layout probe against every release and the tables
must come out identical. Without that folder only the structural checks run.
"""
import importlib.util
import os
from pathlib import Path
import shutil
import subprocess
import sys
import unittest


ROOT = Path(__file__).resolve().parents[2]
GENERATOR = ROOT / "scripts/generate-ffmpeg-system-layouts.py"
TABLES = ROOT / "plugins/midnight-thumbnail-video/src/system/linux/ffmpeg/layouts.rs"


def generator():
    spec = importlib.util.spec_from_file_location("ffmpeg_system_layouts", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class GeneratedTables(unittest.TestCase):
    def test_every_series_and_field_is_in_the_generated_tables(self):
        module = generator()
        text = TABLES.read_text(encoding="utf-8")
        self.assertTrue(text.startswith("// @generated by scripts/generate-ffmpeg-system-layouts.py"))
        for major, releases in module.RELEASES.items():
            self.assertIn(f"// FFmpeg {' and '.join(releases)}\n", text)
            self.assertIn(f"        avcodec: {major},\n", text)
        for name, _, _ in module.FIELDS:
            self.assertEqual(text.count(f"        {name}: "), len(module.RELEASES), name)
        for function in module.PRESENCE:
            self.assertEqual(text.count(f"        has_{function}: "), len(module.RELEASES), function)

    @unittest.skipUnless(os.environ.get("MIDNIGHT_FFMPEG_HEADERS"), "MIDNIGHT_FFMPEG_HEADERS is not set")
    @unittest.skipUnless(shutil.which(os.environ.get("CC", "cc")), "no C compiler")
    def test_the_tables_match_every_release_header(self):
        headers = Path(os.environ["MIDNIGHT_FFMPEG_HEADERS"])
        for releases in generator().RELEASES.values():
            for release in releases:
                self.assertTrue((headers / release / "libavcodec/avcodec.h").is_file(), release)
        result = subprocess.run(
            [sys.executable, "-B", str(GENERATOR), str(headers), "--check", str(TABLES)],
            capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)


if __name__ == "__main__":
    unittest.main()
